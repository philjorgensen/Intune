<#
    .SYNOPSIS
    Changes the BIOS supervisor password with the Lenovo.BIOS.Config module.

    .DESCRIPTION
    Imports the Lenovo.BIOS.Config module packaged next to this script, locates the encrypted password
    change (.ini) file generated by the Think BIOS Config Tool V2, and applies it with
    Import-LnvPasswordChangeFile. Exits 3010 on success so Intune performs a soft reboot.

    A supervisor password must already be set on the device.

    .NOTES
    Set $SecretKey to the passphrase used when the password change file was generated.
    Log: %ProgramData%\Lenovo\ThinkBiosConfig\Logs\PasswordChange.log
#>

$ErrorActionPreference = 'Stop'

# === Log File ===
$LogFile = "$env:ProgramData\Lenovo\ThinkBiosConfig\Logs\PasswordChange.log"
$LogDir = Split-Path $LogFile -Parent
if (-not (Test-Path $LogDir)) { New-Item -ItemType Directory -Path $LogDir -Force | Out-Null }

# === Write-SvpLog Function ===
function Write-SvpLog
{
    param (
        [Parameter(Mandatory = $true)]
        [string]$Message,
        [ValidateSet('INFO', 'WARN', 'ERROR', 'SUCCESS')]
        [string]$Level = 'INFO'
    )
    $timestamp = Get-Date -Format 'yyyy-MM-dd HH:mm:ss'
    $logEntry = "$timestamp [$Level]: $Message"
    Add-Content -Path $LogFile -Value $logEntry -Encoding UTF8
}

# === Initial log entry ===
Write-SvpLog "=== LENOVO PASSWORD CHANGE CONFIG INSTALL STARTED ===" 'INFO'

# --- Paths ---
$ModulePath = Join-Path $PSScriptRoot 'Lenovo.BIOS.Config\*\*.psd1'

# --- Secret Key ---
$SecretKey = "secretkey"  # Secret key for decryption - update as needed

# -------------------------------------------------
# 1. Load Lenovo BIOS Config Module
# -------------------------------------------------
try
{
    $ModuleFile = Get-Item $ModulePath | Select-Object -First 1
    if (-not $ModuleFile) { throw "No .psd1 module found in $ModulePath" }

    Import-Module $ModuleFile.FullName -Force
    Write-SvpLog "Loaded module: $($ModuleFile.Directory.Name)" 'SUCCESS'
}
catch
{
    Write-SvpLog "Failed to load Lenovo BIOS Config module: $($_.Exception.Message)" 'ERROR'
    exit 1
}

# -------------------------------------------------
# 2. Verify Password Change File
# -------------------------------------------------
try
{
    $ConfigFile = Get-ChildItem -Path $PSScriptRoot -Filter "*.ini" | Select-Object -First 1
    if (-not $ConfigFile) { throw "No .ini file found in $PSScriptRoot" }
    $ConfigFilePath = $ConfigFile.FullName
    Write-SvpLog "Found password change file: $ConfigFilePath" 'INFO'
}
catch
{
    Write-SvpLog "Failed to find password change file: $($_.Exception.Message)" 'ERROR'
    exit 1
}

# -------------------------------------------------
# 3. Import Password Change File
# -------------------------------------------------
try
{
    Import-LnvPasswordChangeFile -ConfigFile $ConfigFilePath -Key $SecretKey | Out-Null
    Write-SvpLog "Password change configuration imported successfully." 'SUCCESS'

    Write-SvpLog "=== PASSWORD CHANGE CONFIG INSTALL COMPLETE (Exit 3010) ===" 'SUCCESS'
    exit 3010
}
catch
{
    Write-SvpLog "EXCEPTION during password change import: $($_.Exception.Message)" 'ERROR'
    exit 1
}
